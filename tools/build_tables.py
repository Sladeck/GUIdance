#!/usr/bin/env python3
"""
Maintainer tool: regenerate GUIdance's precomputed palette tables.

  python3 tools/build_tables.py

Writes skills/guidance/references/palettes/<variant>.md. Each file has one row per
HSL hue (0 to 355, 5 degree steps) plus a "grey" row, with every colour role in
light and dark. The seed for row h is hsl(h, 75%, 45%); scheme variants depend
only on the seed's hue (and, for vibrant, a chroma floor), so the brand colour's
saturation and lightness do not change the row. Every row is checked against
WCAG (120 role pairs); the build fails if any pair fails.

Users of the skill never run this: the tables are data the skill reads directly.
"""
import colorsys
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import palette as P  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "skills", "guidance", "references", "palettes")
VARIANTS = ["tonal_spot", "neutral", "vibrant", "expressive", "two_tone"]
ROLE_ORDER = list(P.ROLES.keys()) + [f"chart-{i}" for i in range(1, 6)]
BLURB = {
    "tonal_spot": "Calm, balanced (Material's default). Brand hue at moderate colourfulness, a softer secondary, a tertiary 60 degrees away.",
    "neutral": "Quiet, near-greyscale with a hint of the brand hue. Serious tools, dense data, editorial.",
    "vibrant": "Bold and saturated primary at the brand hue. Consumer apps, marketing, playful products.",
    "expressive": "Primary moved 240 degrees away from the brand hue. Only when there is no brand colour to respect.",
    "two_tone": "Deep, muted brand colour plus a bright accent 45 degrees toward yellow-green (green gets lime, blue gets cyan, red gets amber; a yellow-green brand gets amber) in the secondary roles, with near-neutral surfaces. Dashboards and products that want one strong highlight colour.",
}


def hsl_seed(h):
    r, g, b = colorsys.hls_to_rgb(h / 360, 0.45, 0.75)
    return P.rgb_to_hex((r, g, b))


def grey_scheme():
    real = P.palettes_for
    def mono(hue, variant):
        p = real(250, "tonal_spot")
        for k in ("primary", "secondary", "tertiary", "neutral", "neutral_variant"):
            p[k] = (250, 0)
        return p
    P.palettes_for = mono
    try:
        out = P.build("#666666", "tonal_spot")
    finally:
        P.palettes_for = real
    for i, h in enumerate(P.chart_hues(250), 1):
        out["light"][f"chart-{i}"] = P.tone_color(h, 60, P.CHART_TONES[0])
        out["dark"][f"chart-{i}"] = P.tone_color(h, 50, P.CHART_TONES[1])
    return out


def row(label, scheme):
    fails = [c for c in P.checks(scheme) if not c["pass"]]
    if fails:
        raise SystemExit(f"{label}: {len(fails)} WCAG failures, first: {fails[0]}")
    L = " ".join(f"{r}={scheme['light'][r]}" for r in ROLE_ORDER)
    D = " ".join(f"{r}={scheme['dark'][r]}" for r in ROLE_ORDER)
    return f"{label} | light: {L} | dark: {D}"


def main():
    os.makedirs(OUT, exist_ok=True)
    grey = grey_scheme()
    for v in VARIANTS:
        lines = [f"# Palette table: {v}", "",
                 BLURB[v], "",
                 "Generated by tools/build_tables.py from the Material 3 colour system (role tones from material-color-utilities spec 2021; tone = CIE L*, hue and chroma in OKLCH). Every row passes all 120 WCAG role-pair checks in light and dark.", "",
                 "How to use: compute the brand colour's HSL hue (see `../design-data.md`, section 10), round to the nearest multiple of 5 (360 becomes 0), and read the single line that starts with `h<hue>` (three digits, e.g. `h035`). Use `grey` when the brand has HSL saturation under 12% or is black, white or grey. Copy values exactly; never edit hex codes by hand.", "",
                 "Row format: `h<hue> | light: role=#hex ... | dark: role=#hex ...`", "",
                 "Roles: " + ", ".join(ROLE_ORDER), "", "```"]
        for h in range(0, 360, 5):
            lines.append(row(f"h{h:03d}", P.build(hsl_seed(h), v)))
        lines.append(row("grey", grey))
        lines.append("```")
        with open(os.path.join(OUT, f"{v}.md"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines) + "\n")
        print(f"wrote {v}.md ({len(lines)} lines)")


if __name__ == "__main__":
    main()
