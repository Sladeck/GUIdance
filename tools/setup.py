#!/usr/bin/env python3
"""
Set up GUIdance design tokens in a project.

  python3 setup.py detect   [project_dir] [--json]
  python3 setup.py generate [project_dir] [--target T] [--out PATH] [--type subset|full]
                            [--replace] [--base] [--lang ts|js] [--write] [--force]

detect
  Finds the stack (Tailwind v4 or v3, MUI, SCSS, plain CSS; Next, Vite, Vue...),
  the global stylesheet or theme file, and the tokens the project already has
  (spacing, radius, type sizes, durations, easing). Flags existing values that
  sit off the Material 3 scales. Recommends a target and an output path.

generate
  Writes a token file in the format of the target, with values taken from the
  skill's rules:
    spacing   Material 3 spacing tokens (8dp base, nested 2/4/6/10)  [M3-SPACING A]
    radius    Material 3 corner scale 0..48 + full                    [M3-SHAPE A]
    type      Material 3 type scale (subset of 5 by default, or full 15) [M3-TYPE A]
    motion    Material 3 durations and CSS easing curves              [M3-MOTION A]
    targets   24px minimum (WCAG 2.5.8) and 44px touch (Apple)        [WCAG-2.5.8 S, APPLE-A11Y A]
    focus     focus ring width and offset (colour left to the project) [WCAG-2.2 S]
    measure   60ch text measure (65ch renders ~80+ chars in Arial)    [BAY-LINE A, judgment]
  Colours are never generated: they are the brand's. Check them with contrast.py.

  Targets
    css        :root custom properties (plain CSS, CSS modules, any framework)
    tailwind4  @theme block (utilities like rounded-ui-md, text-ui-body) + :root extras
    tailwind3  a preset file for tailwind.config (presets: [require(...)])
    mui        a ThemeOptions object to deepmerge into createTheme
    scss       Sass variables + the same :root custom properties

  Safety
    Dry run by default: prints the file. --write creates it. An existing file is
    never overwritten without --force. The script never edits existing project
    files; it prints the one line to add (import, preset or merge) instead.
    Tailwind and MUI output uses ui- prefixed names so default utilities and
    existing components do not change; --replace overrides the defaults instead.
"""
import argparse
import json
import os
import re
import sys

SKIP_DIRS = {"node_modules", ".git", ".next", "dist", "build", "out", ".nuxt", ".svelte-kit",
             "coverage", ".turbo", ".vercel", ".cache", "vendor", ".venv", "venv", "__pycache__",
             "storybook-static", "public"}

# ---------------- token values (from references/rules.md) ----------------

SPACING = [("0", 0), ("25", 2), ("50", 4), ("75", 6), ("100", 8), ("125", 10), ("150", 12), ("175", 14),
           ("200", 16), ("250", 20), ("300", 24), ("400", 32), ("450", 36), ("500", 40), ("600", 48),
           ("700", 56), ("800", 64), ("900", 72)]
RADIUS = [("none", "0"), ("xs", "4px"), ("sm", "8px"), ("md", "12px"), ("lg", "16px"), ("lg-plus", "20px"),
          ("xl", "28px"), ("xl-plus", "32px"), ("2xl", "48px"), ("full", "9999px")]
# name: (size rem, line-height rem, weight)
TYPE_FULL = [
    ("display-lg", 3.5625, 4.0, 400), ("display-md", 2.8125, 3.25, 400), ("display-sm", 2.25, 2.75, 400),
    ("headline-lg", 2.0, 2.5, 400), ("headline-md", 1.75, 2.25, 400), ("headline-sm", 1.5, 2.0, 400),
    ("title-lg", 1.375, 1.75, 400), ("title-md", 1.0, 1.5, 500), ("title-sm", 0.875, 1.25, 500),
    ("body-lg", 1.0, 1.5, 400), ("body-md", 0.875, 1.25, 400), ("body-sm", 0.75, 1.0, 400),
    ("label-lg", 0.875, 1.25, 500), ("label-md", 0.75, 1.0, 500), ("label-sm", 0.6875, 1.0, 500),
]
# Default product subset: 5 styles, body at 16px (web default), clear steps.
TYPE_SUBSET = [
    ("headline", 2.0, 2.5, 400), ("title", 1.375, 1.75, 400), ("body", 1.0, 1.5, 400),
    ("body-sm", 0.875, 1.25, 400), ("label", 0.75, 1.0, 500),
]
DURATIONS = [("short-1", 50), ("short-2", 100), ("short-3", 150), ("short-4", 200), ("medium-1", 250),
             ("medium-2", 300), ("medium-3", 350), ("medium-4", 400), ("long-1", 450), ("long-2", 500),
             ("long-3", 550), ("long-4", 600)]
EASING = [("standard", "cubic-bezier(0.2, 0, 0, 1)"), ("standard-decelerate", "cubic-bezier(0, 0, 0, 1)"),
          ("standard-accelerate", "cubic-bezier(0.3, 0, 1, 1)"),
          ("emphasized-decelerate", "cubic-bezier(0.05, 0.7, 0.1, 1)"),
          ("emphasized-accelerate", "cubic-bezier(0.3, 0, 0.8, 0.15)")]
ON_SCALE = {"spacing": {v for _, v in SPACING}, "radius": {0, 4, 8, 12, 16, 20, 28, 32, 48},
            "type": {11, 12, 14, 16, 22, 24, 28, 32, 36, 45, 57},
            "duration": {v for _, v in DURATIONS} | {700, 800, 900, 1000}}

HEADER = ("GUIdance design tokens. Generated by guidance/scripts/setup.py.\n"
          "Sources: Material 3 spacing, shape, type and motion tokens; WCAG 2.2 (2.5.8, focus);\n"
          "Apple HIG accessibility. Colours only when a palette was chosen (palette.py); otherwise\n"
          "keep the brand's and check them with guidance/scripts/contrast.py. Edit values freely; keep the names.")


def rem(x):
    return f"{x:g}rem"


# ---------------- detection ----------------

def walk(root, exts, limit=4000):
    found = []
    for d, dirs, files in os.walk(root):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS and not x.startswith(".")]
        for f in files:
            if f.endswith(exts):
                found.append(os.path.join(d, f))
                if len(found) >= limit:
                    return found
    return found


def read(p, n=400_000):
    try:
        with open(p, encoding="utf-8", errors="replace") as fh:
            return fh.read(n)
    except OSError:
        return ""


def major(v):
    m = re.search(r"(\d+)", v or "")
    return int(m.group(1)) if m else None


def classify_token(name):
    n = name.lower()
    if re.search(r"(dur|duration|delay)", n):
        return "duration"
    if re.search(r"(ease|easing|curve|timing)", n):
        return "easing"
    if re.search(r"(radius|rounded|corner|(^|-)r-)", n):
        return "radius"
    if re.search(r"(font-size|text-|(^|-)fs-|type-|typescale|(^|-)size-(xs|sm|md|lg|xl|\d))", n) and "color" not in n:
        return "type"
    if re.search(r"(space|spacing|gap|gutter|pad|inset|margin|(^|-)sp-)", n):
        return "spacing"
    return None


def px_value(v):
    v = v.strip()
    m = re.fullmatch(r"(-?\d*\.?\d+)px", v)
    if m:
        return float(m.group(1))
    m = re.fullmatch(r"(-?\d*\.?\d+)rem", v)
    if m:
        return float(m.group(1)) * 16
    if re.fullmatch(r"0", v):
        return 0.0
    return None


def ms_value(v):
    m = re.fullmatch(r"(\d*\.?\d+)(ms|s)", v.strip())
    if not m:
        return None
    return float(m.group(1)) * (1000 if m.group(2) == "s" else 1)


def detect(root):
    root = os.path.abspath(root)
    pkg_path = os.path.join(root, "package.json")
    pkg = {}
    if os.path.exists(pkg_path):
        try:
            pkg = json.loads(read(pkg_path))
        except json.JSONDecodeError:
            pkg = {}
    deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}

    stack = {
        "framework": next((f for f, k in [("next", "next"), ("nuxt", "nuxt"), ("sveltekit", "@sveltejs/kit"),
                                          ("astro", "astro"), ("remix", "@remix-run/react"), ("vue", "vue"),
                                          ("svelte", "svelte"), ("angular", "@angular/core"),
                                          ("react", "react")] if k in deps), None),
        "tailwind": None, "mui": "@mui/material" in deps, "sass": "sass" in deps or "node-sass" in deps,
        "css_in_js": next((k for k in ("styled-components", "@emotion/react", "@vanilla-extract/css",
                                       "@stitches/react", "@pandacss/dev") if k in deps), None),
        "native": None,
    }
    if "react-native" in deps or "expo" in deps:
        stack["native"] = "react-native"
    if os.path.exists(os.path.join(root, "pubspec.yaml")):
        stack["native"] = "flutter"
    if any(f.endswith((".xcodeproj", ".xcworkspace")) for f in os.listdir(root)):
        stack["native"] = "ios"

    css_files = walk(root, (".css", ".scss", ".sass", ".pcss"))
    tw_major = major(deps.get("tailwindcss"))
    tw4_css = [f for f in css_files if re.search(r"@import\s+['\"]tailwindcss['\"]", read(f, 20000))]
    tw3_css = [f for f in css_files if "@tailwind base" in read(f, 20000) or "@tailwind utilities" in read(f, 20000)]
    tw_config = next((os.path.join(root, f) for f in os.listdir(root) if re.fullmatch(r"tailwind\.config\.(js|cjs|mjs|ts)", f)), None)
    if tw4_css or (tw_major and tw_major >= 4):
        stack["tailwind"] = 4
    elif tw3_css or tw_config or tw_major == 3:
        stack["tailwind"] = 3

    # Global stylesheet: tailwind entry, else common paths, else most-imported css.
    common = ["app/globals.css", "src/app/globals.css", "styles/globals.css", "src/styles/globals.css",
              "src/index.css", "src/main.css", "src/styles.css", "src/app.css", "assets/css/main.css",
              "src/assets/main.css", "src/styles/global.scss", "styles/globals.scss", "src/index.scss",
              "src/styles/globals.scss", "src/app/globals.scss"]
    entry = (tw4_css or tw3_css or [None])[0]
    if not entry:
        for lay in walk(root, ("layout.tsx", "layout.jsx", "layout.js", "_app.tsx", "_app.jsx", "main.tsx", "main.ts", "main.jsx", "main.js")):
            m = re.search(r"import\s+['\"]([^'\"]+\.s?css)['\"]", read(lay, 20000))
            if m:
                p = m.group(1)
                cand = os.path.normpath(os.path.join(root, "src", p[2:]) if p.startswith("@/") else
                                        os.path.join(os.path.dirname(lay), p) if p.startswith(".") else os.path.join(root, p))
                if os.path.exists(cand):
                    entry = cand
                    break
    if not entry:
        entry = next((os.path.join(root, c) for c in common if os.path.exists(os.path.join(root, c))), None)

    # MUI theme file
    mui_theme = None
    if stack["mui"]:
        for f in walk(root, (".ts", ".tsx", ".js", ".jsx"), limit=6000):
            if "createTheme(" in read(f, 200000):
                mui_theme = f
                break

    # Existing tokens: CSS custom properties, Sass variables, and token source
    # files (tokens.ts / design-tokens.json) that often feed both.
    raw = {}       # name -> (value, file)
    for f in css_files:
        txt = re.sub(r"/\*.*?\*/", "", read(f), flags=re.S)
        for m in re.finditer(r"(--[\w-]+|\$[\w-]+)\s*:\s*([^;{}]+);", txt):
            raw.setdefault(m.group(1), (m.group(2).strip(), os.path.relpath(f, root)))
    token_sources = []
    for f in walk(root, (".ts", ".js", ".mjs", ".cjs", ".json"), limit=8000):
        base = os.path.basename(f).lower()
        if not re.search(r"(^|[-_.])(tokens?|design-tokens|theme-tokens)\.", base) or base == "package.json":
            continue
        token_sources.append(os.path.relpath(f, root))
        txt = re.sub(r"/\*.*?\*/", "", read(f), flags=re.S)
        for m in re.finditer(r"['\"]?([A-Za-z][\w-]*)['\"]?\s*:\s*['\"]([^'\"\n]+)['\"]", txt):
            raw.setdefault("tok:" + m.group(1), (m.group(2).strip(), os.path.relpath(f, root)))

    def resolve_val(val, depth=0):
        m = re.fullmatch(r"var\(\s*(--[\w-]+)\s*(?:,\s*([^)]+))?\)", val.strip())
        if not m or depth > 8:
            return val
        name = m.group(1)
        if name in raw:
            return resolve_val(raw[name][0], depth + 1)
        # token files often emit --prefix-key from key: match on the key suffix
        bare = name[2:]
        for k, (v, _) in raw.items():
            if k.startswith("tok:") and (bare == k[4:] or bare.endswith("-" + k[4:])):
                return resolve_val(v, depth + 1)
        return m.group(2).strip() if m.group(2) else val

    SIZE_RE = re.compile(r"^-?\d*\.?\d+(px|rem|em)$|^clamp\(|^calc\(")
    COLOUR_RE = re.compile(r"^(#|rgb|hsl|oklch|oklab|lab\(|lch\(|color-mix|color\(|transparent$|currentcolor$)", re.I)
    tokens = {"spacing": [], "radius": [], "type": [], "duration": [], "easing": []}
    seen = set()
    for name, (val, file) in raw.items():
        label = name[4:] if name.startswith("tok:") else name
        cat = classify_token(label.lstrip("-$"))
        if not cat:
            continue
        res = resolve_val(val)
        if COLOUR_RE.match(res.strip()):
            continue
        if cat in ("type", "spacing", "radius") and not SIZE_RE.match(res.strip()):
            continue
        key = (label.lstrip("-$").split("-", 1)[-1] if label.startswith(("--", "$")) else label, res)
        if key in seen:
            continue
        seen.add(key)
        item = {"name": label, "value": res if res == val else f"{res}  (via {val})", "file": file,
                "alias": res != val}
        px = px_value(res)
        if cat in ("spacing", "radius", "type") and px is not None and px >= 0:
            item["px"] = px
            item["on_scale"] = True if (cat == "radius" and px >= 999) else px in ON_SCALE[cat]
            if not item["on_scale"]:
                item["nearest"] = min(sorted(ON_SCALE[cat]), key=lambda v: (abs(v - px), -v))
        if cat == "duration":
            ms = ms_value(res)
            if ms is not None:
                item["ms"] = ms
                item["on_scale"] = ms in ON_SCALE["duration"]
                if not item["on_scale"]:
                    item["nearest"] = min(sorted(ON_SCALE["duration"]), key=lambda v: (abs(v - ms), -v))
        tokens[cat].append(item)

    # Recommendation
    if stack["native"]:
        target, note = None, f"{stack['native']} project: setup.py writes web tokens only. Use the rules by hand (Apple HIG / Material values)."
    elif stack["tailwind"] == 4:
        target, note = "tailwind4", "Tailwind v4: tokens go in an @theme block imported after @import \"tailwindcss\"."
    elif stack["tailwind"] == 3:
        target, note = "tailwind3", "Tailwind v3: tokens go in a preset added to tailwind.config presets."
    elif stack["mui"]:
        target, note = "mui", "MUI: tokens go in ThemeOptions deep-merged into createTheme." + \
            (" A plain CSS file can be added too for non-MUI styles (target css)." if css_files else "")
    elif stack["sass"] and entry and entry.endswith((".scss", ".sass")):
        target, note = "scss", "Sass: tokens as Sass variables plus :root custom properties."
    else:
        target, note = "css", "Plain CSS: tokens as :root custom properties imported into the global stylesheet."

    if target == "mui" and mui_theme:
        out_dir = os.path.dirname(mui_theme)
    else:
        out_dir = os.path.dirname(entry) if entry else (os.path.dirname(mui_theme) if mui_theme else root)
    out_name = {"tailwind4": "guidance.css", "css": "guidance.css", "scss": "_guidance.scss",
                "tailwind3": "guidance.preset.js",
                "mui": "guidanceTheme." + ("ts" if "typescript" in deps else "js")}.get(target)
    if target == "tailwind3":
        out_dir = root
    out = os.path.relpath(os.path.join(out_dir, out_name), root) if out_name else None

    # Aliases (a Sass/CSS variable that only points at another token) are kept
    # but not counted when the source token is also present.
    for cat, items in tokens.items():
        sources = {(i["px"] if "px" in i else i.get("ms"), ) for i in items if not i["alias"]}
        if sources:
            items.sort(key=lambda i: i["alias"])
    existing = {k: len([i for i in v if not i["alias"]]) or len(v) for k, v in tokens.items()}
    return {
        "root": root, "stack": stack, "entry_stylesheet": os.path.relpath(entry, root) if entry else None,
        "tailwind_config": os.path.relpath(tw_config, root) if tw_config else None,
        "mui_theme_file": os.path.relpath(mui_theme, root) if mui_theme else None,
        "recommended_target": target, "recommended_out": out, "note": note,
        "existing_token_counts": existing, "existing_tokens": tokens,
        "has_design_system": sum(existing.values()) >= 6,
        "token_sources": token_sources[:10],
    }


# ---------------- generators ----------------

def css_root_block(type_set, base, indent="  ", include=("spacing", "radius", "type", "motion", "targets", "focus")):
    L = [":root {"]
    if "spacing" in include:
        L.append(f"{indent}/* Spacing: Material 3 tokens, 8px base (space-100), nested 2/4/6/10 for component internals. */")
        for n, v in SPACING:
            L.append(f"{indent}--space-{n}: {v}px;")
    if "radius" in include:
        L.append(f"\n{indent}/* Radius: Material 3 corner scale. Nested corners: inner = outer - padding. */")
        for n, v in RADIUS:
            L.append(f"{indent}--radius-{n}: {v};")
    if "type" in include:
        L.append(f"\n{indent}/* Type: Material 3 scale ({'full 15 styles' if type_set is TYPE_FULL else 'product subset of 5'}). Body 16px. */")
        for n, s, lh, w in type_set:
            L.append(f"{indent}--text-{n}: {rem(s)};")
            L.append(f"{indent}--text-{n}-line-height: {rem(lh)};")
            L.append(f"{indent}--text-{n}-weight: {w};")
    L.append(f"{indent}--leading-prose: 1.5;")
    L.append(f"{indent}--measure: 60ch; /* about 70 to 75 characters in most sans fonts; check with type-audit.js */")
    L.append(f"\n{indent}/* Motion: Material 3 durations and easing. */")
    for n, v in DURATIONS:
        L.append(f"{indent}--duration-{n}: {v}ms;")
    if "motion" in include:
        for n, v in EASING:
            L.append(f"{indent}--ease-{n}: {v};")
    L.append(f"\n{indent}/* Targets: 24px is the WCAG 2.5.8 floor; 44px is the touch comfort size (Apple 44pt, Material 48dp). */")
    L.append(f"{indent}--target-min: 24px;")
    L.append(f"{indent}--target-touch: 44px;")
    L.append(f"\n{indent}/* Focus: colour must reach 3:1 against what it sits on (WCAG 1.4.11). Set it to your accent. */")
    L.append(f"{indent}--focus-ring-width: 2px;")
    L.append(f"{indent}--focus-ring-offset: 2px;")
    L.append(f"{indent}--focus-ring-color: Highlight;")
    L.append(f"{indent}--scroll-padding-top: 0px; /* set to the sticky header height (WCAG 2.4.11) */")
    L.append("}")
    L.append("")
    L.append("/* Reduced motion: shorten movement, keep fades (Apple HIG, WCAG C39). */")
    L.append("@media (prefers-reduced-motion: reduce) {")
    L.append("  :root {")
    for n, _ in DURATIONS:
        if n.startswith(("medium", "long")):
            L.append(f"    --duration-{n}: 150ms;")
    L.append("  }")
    L.append("}")
    if base:
        L += ["", "/* Base rules (opt-in). Remove any that clash with existing styles. */",
              "html { scroll-padding-top: var(--scroll-padding-top); }",
              ":where(p, li, dd, blockquote, figcaption) { max-width: var(--measure); }",
              ":where(p) { line-height: var(--leading-prose); }",
              ":focus-visible { outline: var(--focus-ring-width) solid var(--focus-ring-color); outline-offset: var(--focus-ring-offset); }",
              "@media (prefers-reduced-motion: reduce) { html { scroll-behavior: auto; } }"]
    return "\n".join(L) + "\n"


def gen_css(type_set, base, palette=None, **_):
    out = f"/*\n{HEADER}\n*/\n\n" + css_root_block(type_set, base)
    return out + ("\n" + css_colour_block(palette) if palette else "")


def gen_scss(type_set, base, palette=None, **_):
    L = [f"/*\n{HEADER}\n*/", ""]
    for n, v in SPACING:
        L.append(f"$space-{n}: {v}px;")
    L.append("")
    for n, v in RADIUS:
        L.append(f"$radius-{n}: {v};")
    L.append("")
    for n, s, lh, w in type_set:
        L.append(f"$text-{n}: {rem(s)};  $text-{n}-line-height: {rem(lh)};  $text-{n}-weight: {w};")
    L.append("")
    for n, v in DURATIONS:
        L.append(f"$duration-{n}: {v}ms;")
    for n, v in EASING:
        L.append(f"$ease-{n}: {v};")
    L += ["$target-min: 24px;", "$target-touch: 44px;", "$measure: 60ch;", "",
          "// The same values as CSS custom properties, for runtime theming.", ""]
    if palette:
        L.append("")
        L += [f"$color-{r}: var(--color-{r});" for r in palette["roles"]]
    return "\n".join(L) + "\n" + css_root_block(type_set, base) + ("\n" + css_colour_block(palette) if palette else "")


def gen_tailwind4(type_set, base, replace=False, palette=None, **_):
    p = "" if replace else "ui-"
    L = [f"/*\n{HEADER}\nImport this file right after @import \"tailwindcss\".\n"
         f"Utilities: rounded-{p}md, text-{p}body, ease-standard, min-h-(--target-touch) ...\n"
         "Spacing: Tailwind's default --spacing (0.25rem = 4px) already matches the Material 3\n"
         "4/8px grid (p-2 = 8px, p-4 = 16px, p-6 = 24px). It is left unchanged.\n*/", "", "@theme {"]
    for n, v in RADIUS:
        L.append(f"  --radius-{p}{n}: {v};")
    L.append("")
    for n, s, lh, w in type_set:
        L.append(f"  --text-{p}{n}: {rem(s)};")
        L.append(f"  --text-{p}{n}--line-height: {rem(lh)};")
        L.append(f"  --text-{p}{n}--font-weight: {w};")
    L.append("")
    for n, v in EASING:
        L.append(f"  --ease-{n}: {v};")
    if palette:
        L.append("")
        L.append("  /* Colours (light). Utilities: bg-primary, text-on-surface, border-outline ... */")
        L += [f"  --color-{r}: {palette['light'][r]};" for r in palette["roles"]]
    L.append("}")
    if palette:
        dark = "\n".join(f"    --color-{r}: {palette['dark'][r]};" for r in palette["roles"])
        L.append("")
        L.append("/* Dark colours: follow the OS unless data-theme is set on <html>.\n"
                 "   To make Tailwind's dark: variant follow data-theme too, add to your entry CSS:\n"
                 "   @custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *)); */")
        L.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n" + dark + "\n  }\n}")
        L.append("[data-theme=\"dark\"] {\n" + dark.replace("    ", "  ") + "\n}")
    L.append("")
    L.append("/* Values Tailwind has no theme namespace for (durations, targets, focus, measure).\n"
             "   Named so they do not collide with Tailwind's own --radius-*, --text-* or --ease-* variables. */")
    L.append(css_root_block(type_set, base, include=("spacing", "targets", "focus")))
    return "\n".join(L) + "\n"


def gen_tailwind3(type_set, base, replace=False, lang="js", palette=None, **_):
    p = "" if replace else "ui-"
    radius = ",\n".join(f"        '{p}{n}': '{v}'" for n, v in RADIUS)
    fonts = ",\n".join(f"        '{p}{n}': ['{rem(s)}', {{ lineHeight: '{rem(lh)}', fontWeight: '{w}' }}]"
                       for n, s, lh, w in type_set)
    durs = ",\n".join(f"        '{n}': '{v}ms'" for n, v in DURATIONS)
    eases = ",\n".join(f"        '{n}': '{v}'" for n, v in EASING)
    key = "theme: {\n    " + ("" if replace else "extend: {\n      ")
    close = "    },\n  }" if not replace else "  }"
    body = (f"/*\n{HEADER}\nAdd to tailwind.config: presets: [require('./guidance.preset.js')]\n"
            "Spacing: Tailwind's default 4px step already matches the Material 3 grid, so it is unchanged.\n*/\n"
            "module.exports = {\n  " + key +
            f"borderRadius: {{\n{radius}\n      }},\n"
            f"      fontSize: {{\n{fonts}\n      }},\n"
            f"      transitionDuration: {{\n{durs}\n      }},\n"
            f"      transitionTimingFunction: {{\n{eases}\n      }},\n"
            "      minWidth: { target: '24px', touch: '44px' },\n"
            "      minHeight: { target: '24px', touch: '44px' },\n"
            "      maxWidth: { measure: '60ch' },\n"
            + (("      colors: {\n" + ",\n".join(f"        '{r}': 'var(--color-{r})'" for r in palette["roles"]) + "\n      },\n") if palette else "")
            + f"{close}"
            + ((",\n  plugins: [\n    // Colour variables, light and dark (dark follows the OS unless data-theme is set).\n"
                "    function ({ addBase }) {\n      addBase({\n"
                "        ':root': " + json.dumps({f"--color-{r}": palette['light'][r] for r in palette['roles']}) + ",\n"
                "        '@media (prefers-color-scheme: dark)': { ':root:not([data-theme=\"light\"])': " + json.dumps({f"--color-{r}": palette['dark'][r] for r in palette['roles']}) + " },\n"
                "        '[data-theme=\"dark\"]': " + json.dumps({f"--color-{r}": palette['dark'][r] for r in palette['roles']}) + ",\n"
                "      });\n    },\n  ]") if palette else "")
            + "\n};\n")
    return body


def gen_mui(type_set, base, lang="ts", palette=None, **_):
    t = {n: (s, lh, w) for n, s, lh, w in TYPE_FULL}
    def v(name, extra=""):
        s, lh, w = t[name]
        return f"{{ fontSize: '{rem(s)}', lineHeight: '{rem(lh)}', fontWeight: {w}{extra} }}"
    ts = lang == "ts"
    as_const = " as const" if ts else ""
    overline_extra = f", textTransform: 'uppercase'{as_const}"
    button_extra = f", textTransform: 'none'{as_const}"
    head = "import type { ThemeOptions } from '@mui/material/styles';\n\n" if ts else ""
    ann = ": ThemeOptions" if ts else ""
    return (f"/*\n{HEADER}\n\nMerge into your theme:\n"
            "  import { deepmerge } from '@mui/utils';\n"
            "  import { guidanceThemeOptions } from './guidanceTheme';\n"
            "  const theme = createTheme(deepmerge(yourOptions, guidanceThemeOptions));\n"
            "Putting guidanceThemeOptions second lets it win. Put it first to keep your existing values\n"
            "and only fill gaps. This changes heading sizes, the corner radius and button casing app-wide:\n"
            "review the diff before shipping.\n*/\n"
            f"{head}export const guidanceThemeOptions{ann} = {{\n"
            "  // MUI multiplies this: theme.spacing(1) = 8px, (2) = 16px, (0.5) = 4px. Material 3 base is 8.\n"
            "  spacing: 8,\n"
            "  // One radius drives buttons, inputs, cards. 8 = Material 3 'small'. Use 12 for card-heavy UIs.\n"
            "  shape: { borderRadius: 8 },\n"
            "  typography: {\n"
            "    htmlFontSize: 16,\n"
            "    fontSize: 14, // MUI's base for body2 and components; body1 is set to 16 below.\n"
            f"    h1: {v('headline-lg')},\n"
            f"    h2: {v('headline-md')},\n"
            f"    h3: {v('headline-sm')},\n"
            f"    h4: {v('title-lg')},\n"
            f"    h5: {v('title-md')},\n"
            f"    h6: {v('title-sm')},\n"
            f"    subtitle1: {v('title-md')},\n"
            f"    subtitle2: {v('title-sm')},\n"
            f"    body1: {v('body-lg')},\n"
            f"    body2: {v('body-md')},\n"
            f"    caption: {v('body-sm')},\n"
            f"    overline: {v('label-sm', overline_extra)},\n"
            f"    button: {v('label-lg', button_extra)}, // Material 3 labels are sentence case\n"
            "  },\n"
            "  transitions: {\n"
            "    duration: { shortest: 100, shorter: 150, short: 200, standard: 300, complex: 400, enteringScreen: 300, leavingScreen: 200 },\n"
            "    easing: {\n"
            "      easeInOut: 'cubic-bezier(0.2, 0, 0, 1)', // M3 standard\n"
            "      easeOut: 'cubic-bezier(0.05, 0.7, 0.1, 1)', // M3 emphasized decelerate (entering)\n"
            "      easeIn: 'cubic-bezier(0.3, 0, 0.8, 0.15)', // M3 emphasized accelerate (exiting)\n"
            "      sharp: 'cubic-bezier(0.3, 0, 1, 1)', // M3 standard accelerate\n"
            "    },\n"
            "  },\n"
            + (("  // Colours: Material 3 roles mapped to MUI. colorSchemes needs MUI v6 or later.\n"
                "  // If your createTheme options also have a top-level palette, MUI lets that palette win: remove it.\n"
                "  // Switch with useColorScheme(); add cssVariables: { colorSchemeSelector: 'data-theme' } to follow <html data-theme>.\n"
                "  colorSchemes: {\n"
                f"    light: {{\n      palette: {mui_palette(palette['light'], ts)},\n    }},\n"
                f"    dark: {{\n      palette: {mui_palette(palette['dark'], ts)},\n    }},\n"
                "  },\n") if palette else "")
            + "};\n")


# ---------------- colours (from palette.py generate --out) ----------------

def load_palette(path):
    if not path:
        return None
    with open(path, encoding="utf-8") as fh:
        d = json.load(fh)
    roles = [k for k, v in d["light"].items() if isinstance(v, str)]
    return {"name": d.get("name"), "light": d["light"], "dark": d["dark"], "roles": roles}


def css_colour_block(pal, prefix="--color-"):
    def block(scheme, indent):
        return "\n".join(f"{indent}{prefix}{r}: {scheme[r]};" for r in pal["roles"])
    return ("/* Colours: palette \"" + (pal["name"] or "") + "\", Material 3 colour roles, light and dark.\n"
            "   Every text pair reaches 4.5:1 and every boundary or chart colour 3:1 (checked by palette.py).\n"
            "   Dark follows the OS unless data-theme=\"light\" or data-theme=\"dark\" is set on <html>. */\n"
            ":root {\n  color-scheme: light dark;\n" + block(pal["light"], "  ") + "\n}\n"
            "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n" + block(pal["dark"], "    ") + "\n  }\n}\n"
            "[data-theme=\"dark\"] {\n" + block(pal["dark"], "  ") + "\n}\n"
            "[data-theme=\"light\"] { color-scheme: light; }\n[data-theme=\"dark\"] { color-scheme: dark; }\n")


def mui_palette(scheme, ts):
    q = lambda r: "'" + scheme[r] + "'"
    pair = lambda main, on: "{ main: " + q(main) + ", contrastText: " + q(on) + " }"
    lines = [
        "primary: " + pair("primary", "on-primary"),
        "secondary: " + pair("secondary", "on-secondary"),
        "info: " + pair("tertiary", "on-tertiary"),
        "error: " + pair("error", "on-error"),
        "warning: " + pair("warning", "on-warning"),
        "success: " + pair("success", "on-success"),
        "background: { default: " + q("surface") + ", paper: " + q("surface-container-low") + " }",
        "text: { primary: " + q("on-surface") + ", secondary: " + q("on-surface-variant") + " }",
        "divider: " + q("outline-variant"),
    ]
    return "{\n" + "".join("        " + l + ",\n" for l in lines) + "      }"

GENERATORS = {"css": gen_css, "scss": gen_scss, "tailwind4": gen_tailwind4, "tailwind3": gen_tailwind3, "mui": gen_mui}


def wiring(target, out, info):
    entry = info.get("entry_stylesheet")
    rel = None
    if entry and out:
        rel = os.path.relpath(os.path.join(info["root"], out), os.path.dirname(os.path.join(info["root"], entry)))
        if not rel.startswith("."):
            rel = "./" + rel
    if target == "tailwind4":
        return f'In {entry or "your Tailwind entry CSS"}, add right after @import "tailwindcss";:\n  @import "{rel or "./guidance.css"}";'
    if target == "css":
        return (f'In {entry or "your global stylesheet"}, add at the top:\n  @import "{rel or "./guidance.css"}";\n'
                "(or import it from the root layout / main entry file)")
    if target == "scss":
        name = os.path.basename(out).lstrip("_").rsplit(".", 1)[0]
        return f'In {entry or "your global .scss"}, add at the top:\n  @use "{(os.path.dirname(rel) + "/" if rel and os.path.dirname(rel) not in ("", ".") else "./")}{name}" as *;'
    if target == "tailwind3":
        return f"In {info.get('tailwind_config') or 'tailwind.config.js'}, add:\n  presets: [require('./{os.path.basename(out)}')],"
    if target == "mui":
        return (f"In {info.get('mui_theme_file') or 'your theme file'}, wrap the createTheme options:\n"
                "  import { deepmerge } from '@mui/utils';\n"
                f"  import {{ guidanceThemeOptions }} from './{os.path.basename(out).rsplit('.', 1)[0]}';\n"
                "  createTheme(deepmerge(existingOptions, guidanceThemeOptions))")
    return ""


def main():
    ap = argparse.ArgumentParser(description="Set up GUIdance tokens in a project.")
    ap.add_argument("command", choices=["detect", "generate"])
    ap.add_argument("project", nargs="?", default=".")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--target", choices=list(GENERATORS))
    ap.add_argument("--out", help="output path relative to the project")
    ap.add_argument("--type", choices=["subset", "full"], default="subset")
    ap.add_argument("--replace", action="store_true", help="Tailwind: override default utility names instead of ui- prefixed ones")
    ap.add_argument("--base", action="store_true", help="CSS targets: add opt-in base rules (focus ring, measure, scroll padding)")
    ap.add_argument("--lang", choices=["ts", "js"])
    ap.add_argument("--palette", help="palette JSON from palette.py generate --out; adds colour roles (light and dark)")
    ap.add_argument("--write", action="store_true", help="create the file (default is a dry run)")
    ap.add_argument("--force", action="store_true", help="allow overwriting an existing file")
    a = ap.parse_args()

    info = detect(a.project)

    if a.command == "detect":
        if a.json:
            print(json.dumps(info, indent=2))
            return
        s = info["stack"]
        print(f"Project: {info['root']}")
        print(f"Framework: {s['framework'] or 'none detected'}   Tailwind: {s['tailwind'] or 'no'}   MUI: {'yes' if s['mui'] else 'no'}"
              f"   Sass: {'yes' if s['sass'] else 'no'}   CSS-in-JS: {s['css_in_js'] or 'no'}" + (f"   Native: {s['native']}" if s['native'] else ""))
        print(f"Global stylesheet: {info['entry_stylesheet'] or 'not found'}")
        if info["tailwind_config"]:
            print(f"Tailwind config: {info['tailwind_config']}")
        if info["mui_theme_file"]:
            print(f"MUI theme: {info['mui_theme_file']}")
        if info["token_sources"]:
            print(f"Token source files: {', '.join(info['token_sources'])}  (edit values here; CSS/Sass may only reference them)")
        print("\nExisting tokens:")
        for cat, items in info["existing_tokens"].items():
            if not items:
                print(f"  {cat:9} none")
                continue
            primary = [i for i in items if not i["alias"]] or items
            off = [i for i in primary if i.get("on_scale") is False]
            aliases = len(items) - len(primary)
            print(f"  {cat:9} {len(primary)} found" + (f", {len(off)} off the Material 3 scale" if off else "")
                  + (f" (+{aliases} aliases)" if aliases else ""))
            for i in primary[:12]:
                unit = "ms" if cat == "duration" else "px"
                mark = f"  off-scale, nearest {i['nearest']:g}{unit}" if i.get("on_scale") is False else ""
                print(f"      {i['name']}: {i['value']}  ({i['file']}){mark}")
            if len(primary) > 12:
                print(f"      ... {len(primary) - 12} more (use --json)")
        print(f"\nRecommended target: {info['recommended_target']}  ->  {info['recommended_out']}")
        print(info["note"])
        if info["has_design_system"]:
            print("\nThis project already has a token system. Prefer adapting its existing tokens to the scales\n"
                  "(fix the off-scale values, add missing categories) over adding a parallel set.")
        return

    target = a.target or info["recommended_target"]
    if not target:
        sys.exit(info["note"])
    out = a.out or info["recommended_out"] or {"tailwind3": "guidance.preset.js", "mui": "guidanceTheme.ts",
                                               "scss": "_guidance.scss"}.get(target, "guidance.css")
    if a.target and not a.out:
        base_dir = os.path.dirname(info["recommended_out"] or "")
        out = os.path.join(base_dir, {"tailwind3": "guidance.preset.js", "mui": "guidanceTheme." + (a.lang or "ts"),
                                      "scss": "_guidance.scss"}.get(target, "guidance.css"))
    lang = a.lang or ("ts" if out.endswith((".ts", ".tsx")) else "js")
    type_set = TYPE_FULL if a.type == "full" else TYPE_SUBSET
    content = GENERATORS[target](type_set=type_set, base=a.base, replace=a.replace, lang=lang,
                                 palette=load_palette(a.palette))
    path = os.path.join(info["root"], out)

    if not a.write:
        print(f"# DRY RUN: would write {out} (target {target}). Re-run with --write to create it.\n")
        print(content)
    else:
        if os.path.exists(path) and not a.force:
            sys.exit(f"{out} already exists. Not overwriting. Use --force, or --out for another path.")
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        print(f"Wrote {out} (target {target}).")
    print("\nTo wire it up:\n" + wiring(target, out, info))


if __name__ == "__main__":
    main()
